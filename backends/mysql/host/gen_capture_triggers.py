#!/usr/bin/env python3
"""Generate the mutation-capture triggers for a set of tables.

Each table gets AFTER INSERT / DELETE / UPDATE triggers that call the plugin's
self-describing UDF mysql_accel_capture_row(table_id, kind, types, old row...,
new row...). The column type string is derived from information_schema, so the
plugin needs no per-table schema registry: the capture call carries what the
host needs to decode the row.

  type chars: i int64 | u uint64 | n exact decimal | f double | d date | s string
  kind:       0 insert | 1 delete | 2 update

The table ids are the ones the query modules use in Dependencies() (workload
configuration, given here as name=id pairs).

Usage:
  gen_mysql_capture_triggers.py --db DB [--prefix accel_codegen_] \
      --table lineitem=1 --table orders=2 ... > triggers.sql
Connection: ACCEL_MYSQL_DOCKER=1 ACCEL_MYSQL_CONTAINER=<name> runs the mysql
client inside that container; otherwise MYSQL_HOST/MYSQL_PORT/MYSQL_USER on the
host. Password: MYSQL_PWD (else MYSQL_ROOT_PASSWORD).
"""
import argparse
import os
import subprocess
import sys


def mysql_cmd():
    password = os.environ.get("MYSQL_PWD", os.environ.get("MYSQL_ROOT_PASSWORD", ""))
    if os.environ.get("ACCEL_MYSQL_DOCKER") == "1":
        container = os.environ.get("ACCEL_MYSQL_CONTAINER", "accel_mysql_test")
        return ["docker", "exec", "-i", container, "mysql", "-h", "127.0.0.1", "-P", "3306",
                "-uroot", f"-p{password}", "--batch", "--skip-column-names"]
    return ["mysql", "-h", os.environ.get("MYSQL_HOST", "127.0.0.1"),
            "-P", os.environ.get("MYSQL_PORT", "3306"),
            "-u" + os.environ.get("MYSQL_USER", "root"), f"-p{password}",
            "--batch", "--skip-column-names"]


def type_char(data_type, column_type):
    data_type = data_type.lower()
    if data_type in ("tinyint", "smallint", "mediumint", "int", "integer", "bigint"):
        return "u" if "unsigned" in column_type.lower() and data_type == "bigint" else "i"
    if data_type in ("decimal", "numeric"):
        return "n"
    if data_type in ("float", "double", "real"):
        return "f"
    if data_type == "date":
        return "d"
    return "s"


def columns(db, table):
    sql = ("SELECT COLUMN_NAME, DATA_TYPE, COLUMN_TYPE FROM information_schema.COLUMNS "
           f"WHERE TABLE_SCHEMA = '{db}' AND TABLE_NAME = '{table}' ORDER BY ORDINAL_POSITION")
    out = subprocess.run(mysql_cmd() + ["-e", sql], capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(out.stderr)
    rows = [line.split("\t") for line in out.stdout.splitlines() if line.strip()]
    if not rows:
        sys.exit(f"table {db}.{table} not found")
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", required=True)
    ap.add_argument("--prefix", default="accel_codegen_")
    ap.add_argument("--table", action="append", required=True, metavar="NAME=ID")
    args = ap.parse_args()

    print("-- Generated by backends/mysql/host/gen_capture_triggers.py; do not edit.")
    print("DELIMITER //\n")
    for spec in args.table:
        name, _, ident = spec.partition("=")
        cols = columns(args.db, name)
        types = "".join(type_char(c[1], c[2]) for c in cols)
        new = ", ".join(f"NEW.`{c[0]}`" for c in cols)
        old = ", ".join(f"OLD.`{c[0]}`" for c in cols)
        for suffix, event, kind, row in (("i", "INSERT", 0, new), ("d", "DELETE", 1, old),
                                         ("u", "UPDATE", 2, old + ", " + new)):
            trig = f"{args.prefix}{name}_{suffix}"
            print(f"DROP TRIGGER IF EXISTS {trig}//")
            print(f"CREATE TRIGGER {trig} AFTER {event} ON {name}\nFOR EACH ROW\nBEGIN")
            print(f"  SET @accel_cap = mysql_accel_capture_row('{ident}', '{kind}', '{types}', {row});")
            print("END//\n")
    print("DELIMITER ;")


main()
