#!/usr/bin/env python3
"""Generate a benchmark's Verus world crate: ONE verified aux store for every
accelerator of the database (one reader-writer lock, one version per commit,
every accelerator's slot answering for the same database version).

    python3 scripts/gen_verus_world.py tpch tpch_q1_vgen tpch_q2_vgen ...

writes src/generated/<bench>/verus_world/<bench>_world/:
  crate/src/lib.rs     the crate (links every kit crate as an rlib)
  crate/src/world.rs   VERIFIED: the world type, slot replacement, the commit
                       batch, per-accelerator reads with the snapshot theorem
  crate/src/ffi.rs     TRUSTED C ABI (the host's contract is assumed here)
  <bench>_world_verus.h
  world_glue.cpp       registers the C ABI with the host kit (verus_kit.hpp)

Build: scripts/build_verus_world.sh (kits as --rlib first).
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def nest(items, end):
    out = end
    for item in reversed(items):
        out = item(out)
    return out


def main() -> None:
    bench, kits = sys.argv[1], sys.argv[2:]
    if not kits:
        sys.exit("usage: gen_verus_world.py <bench> <kit crate>...")
    world = f"{bench}_world"
    prefix = f"{bench}w"
    out = ROOT / "src" / "generated" / bench / "verus_world" / world
    (out / "crate" / "src").mkdir(parents=True, exist_ok=True)
    n = len(kits)
    idx = range(1, n + 1)

    world_ty = nest([lambda r, k=k: f"Both<Slot<S{k}>, {r}>" for k in idx], "Nothing")
    db_ty = nest([lambda r, k=k: f"(D{k}, {r})" for k in idx], "()")

    def path(k: int, base: str) -> str:  # base.rest.rest...first
        return base + ".rest" * (k - 1) + ".first"

    def db_path(k: int, base: str) -> str:  # base.1.1...0
        return base + ".1" * (k - 1) + ".0"

    def with_db(k: int) -> str:  # d with kit k's component x
        def go(j: int, base: str) -> str:
            if j == k:
                return f"(x, {base}.1)"
            return f"({base}.0, {go(j + 1, base + '.1')})"
        return go(1, "d")

    def replace_expr(k: int) -> str:
        def go(j: int, base: str) -> str:
            if j == k:
                return f"Both {{ first: s, rest: <W{j + 1} as AuxWorld<G{j + 1}>>::share(&{base}.rest) }}"
            return (f"Both {{ first: <Slot<S{j}> as AuxWorld<D{j}>>::share(&{base}.first), "
                    f"rest: {go(j + 1, base + '.rest')} }}")
        return go(1, "w")

    lines = []
    w = lines.append
    w("// GENERATED by scripts/gen_verus_world.py.  DO NOT EDIT: regenerate.")
    w("//")
    w(f"// The {bench} world: one verified aux store for every accelerator (one")
    w("// reader-writer lock, one version per database commit).  Version v's world")
    w("// holds one slot per accelerator; slot k answers for accelerator k's")
    w("// projection of the database at v (`db_k`).  A commit's new version is")
    w("// assembled outside the lock (`Batch`) from the newest version's world and")
    w("// installed with one write-locked step; readers resolve their snapshot")
    w("// under the read lock (substrate store.rs: the snapshot theorem) and take")
    w("// their accelerator's state.")
    w("#![allow(unused_imports)]")
    w("use vstd::prelude::*;")
    w("use std::sync::Arc;")
    w("use verus_substrate::store::*;")
    w("use verus_substrate::world::*;")
    w("")
    w("verus! {")
    w("")
    for k, kit in zip(idx, kits):
        w(f"pub type S{k} = {kit}_verus::kernel::State;")
        w(f"pub type D{k} = {kit}_verus::gen_spec::Db;")
    w("")
    w(f"/// One slot per accelerator ({', '.join(kits)}), flat: the world answers")
    w("/// for a database when every slot answers for its accelerator's projection.")
    w("pub struct World {")
    for k in idx:
        w(f"    pub s{k}: Slot<S{k}>,")
    w("}")
    w("")
    w("/// The database as each accelerator sees it (its projection), side by side.")
    w("pub struct GDb {")
    for k in idx:
        w(f"    pub d{k}: D{k},")
    w("}")
    w("")
    w("impl AuxWorld<GDb> for World {")
    w("    open spec fn ok(self, d: GDb) -> bool {")
    w("        " + "\n        && ".join(f"self.s{k}.ok(d.d{k})" for k in idx))
    w("    }")
    w("")
    w("    fn invalid() -> (w: Self) {")
    w("        World { " + ", ".join(f"s{k}: Slot::Invalid" for k in idx) + " }")
    w("    }")
    w("")
    w("    fn share(&self) -> (w: Self) {")
    w("        World {")
    for k in idx:
        w(f"            s{k}: <Slot<S{k}> as AuxWorld<D{k}>>::share(&self.s{k}),")
    w("        }")
    w("    }")
    w("}")
    w("")
    w("pub type GStore = Store<GDb, World>;")
    w("pub type GPrepared = Prepared<GDb, World>;")
    w("")
    for k, kit in zip(idx, kits):
        others = [j for j in idx if j != k]
        w(f"/// {kit}'s projection of the database.")
        w(f"pub open spec fn db_{k}(d: GDb) -> D{k} {{")
        w(f"    d.d{k}")
        w("}")
        w("")
        w(f"/// d with {kit}'s projection replaced by x.")
        w(f"pub open spec fn with_{k}(d: GDb, x: D{k}) -> GDb {{")
        w("    GDb { " + ", ".join(f"d{j}: x" if j == k else f"d{j}: d.d{j}" for j in idx) + " }")
        w("}")
        w("")
        w(f"/// w with {kit}'s slot replaced by s (every other slot shared).")
        w(f"pub fn replace_{k}(w: &World, s: Slot<S{k}>, Ghost(d): Ghost<GDb>, Ghost(x): Ghost<D{k}>) -> (r: World)")
        w("    requires")
        w("        w.ok(d),")
        w("        s.ok(x),")
        w("    ensures")
        w(f"        r.ok(with_{k}(d, x)),")
        w("{")
        w("    World {")
        for j in idx:
            if j == k:
                w(f"        s{j}: s,")
            else:
                w(f"        s{j}: <Slot<S{j}> as AuxWorld<D{j}>>::share(&w.s{j}),")
        w("    }")
        w("}")
        w("")
        w(f"/// {kit}'s slot of w.")
        w(f"pub fn slot_{k}(w: &World, Ghost(d): Ghost<GDb>) -> (r: &Slot<S{k}>)")
        w("    requires")
        w("        w.ok(d),")
        w("    ensures")
        w(f"        r.ok(db_{k}(d)),")
        w("{")
        w(f"    &w.s{k}")
        w("}")
        w("")
    w("""/// The next version's world, assembled outside the lock from the newest
/// version e's world: each accelerator the commit changes gets its new slot
/// (answering for its projection at e + 1), every other slot is carried.
/// Invariant: the world answers for `target`, the database with each replaced
/// projection at e + 1 and every carried one at e.
pub struct Batch {
    e: u64,
    next: World,
    target: Ghost<GDb>,
    timeline: Ghost<spec_fn(nat) -> GDb>,
}

impl Batch {
    #[verifier::type_invariant]
    spec fn wf(self) -> bool {
        &&& self.e < u64::MAX
        &&& self.next.ok(self.target@)
    }

    pub closed spec fn epoch(self) -> u64 {
        self.e
    }

    pub closed spec fn target(self) -> GDb {
        self.target@
    }

    pub closed spec fn timeline(self) -> spec_fn(nat) -> GDb {
        self.timeline@
    }

    /// The database at the version this batch prepares (e + 1).
    pub open spec fn next_db(self) -> GDb {
        (self.timeline())((self.epoch() + 1) as nat)
    }
}

/// A batch from the newest version (None if no version can follow it).
pub fn batch_new(store: &GStore) -> (r: Option<Batch>)
    ensures
        r matches Some(b) ==> b.timeline() == store.timeline() && b.target() == store.db_at(b.epoch() as nat),
{
    let (e, w) = store.newest_world();
    if e < u64::MAX {
        Some(Batch { e, next: w, target: Ghost(store.db_at(e as nat)), timeline: Ghost(store.timeline()) })
    } else {
        None
    }
}

/// The next version (consumes the batch).  HOST CONTRACT (the requires): the
/// accelerators the batch did not replace are unchanged by this commit, so
/// the target is the database at e + 1.
pub fn batch_finish(b: Batch) -> (p: GPrepared)
    requires
        b.target() == b.next_db(),
    ensures
        p.epoch() == b.epoch(),
        p.timeline() == b.timeline(),
{
    proof {
        use_type_invariant(&b);
    }
    Prepared::new(b.e, b.next, b.timeline)
}
""")
    for k, kit in zip(idx, kits):
        w(f"""/// Replace {kit}'s slot: `s`, a state answering for its projection of
/// the database at e + 1 (the kernel's apply / build proof, from the commit's
/// captured changes), or None (invalid: its queries fall back to SQL).
pub fn batch_set_{k}(b: Batch, s: Option<S{k}>) -> (r: Batch)
    requires
        s matches Some(x) ==> x.answers(db_{k}(b.next_db())),
    ensures
        r.epoch() == b.epoch(),
        r.timeline() == b.timeline(),
        r.target() == with_{k}(b.target(), db_{k}(b.next_db())),
{{
    proof {{
        use_type_invariant(&b);
    }}
    let slot = match s {{
        Some(x) => Slot::Valid(Arc::new(x)),
        None => Slot::Invalid,
    }};
    let next = replace_{k}(&b.next, slot, Ghost(b.target@), Ghost(db_{k}(b.next_db())));
    Batch {{ e: b.e, next, target: Ghost(with_{k}(b.target@, db_{k}(b.next_db()))), timeline: b.timeline }}
}}

/// What a snapshot at engine epoch `at` sees of {kit} (waiting up to
/// `tries` checks for a pending commit), with the version and the window it
/// was decided on.  0: a state, answering for its projection at that version,
/// the version the snapshot rule selects; 1: that version's slot is invalid;
/// 2: a commit in flight may be visible; 3: the version was evicted.
pub fn read_{k}(store: &GStore, at: u64, tries: u64) -> (r: (i32, Option<Arc<S{k}>>, Ghost<u64>, Ghost<Window>))
    ensures
        r.0 == 0 ==> (r.1 matches Some(a) && (*a).answers(db_{k}(store.db_at(r.2@ as nat))) && sees(r.3@, at, r.2@ as int)),
        r.0 == 1 ==> sees(r.3@, at, r.2@ as int),
        r.0 == 2 ==> in_flight(r.3@, at),
        r.0 == 3 ==> none_current(r.3@, at),
        0 <= r.0 <= 3,
{{
    let (res, win) = store.resolve_wait_seen(at, tries);
    match res {{
        Resolved::Found(v, w) => {{
            let s = slot_{k}(&w, Ghost(store.db_at(v as nat)));
            match s.get() {{
                Some(a) => (0, Some(a), Ghost(v), win),
                None => (1, None, Ghost(v), win),
            }}
        }},
        Resolved::Pending => (2, None, Ghost(0), win),
        Resolved::NotVisible => (3, None, Ghost(0), win),
    }}
}}

/// {kit}'s state in the newest version (what its next state is applied
/// to), answering for its projection there; None if invalid.
pub fn newest_{k}(store: &GStore) -> (r: (Option<Arc<S{k}>>, Ghost<u64>))
    ensures
        r.0 matches Some(a) ==> (*a).answers(db_{k}(store.db_at(r.1@ as nat))),
{{
    let (e, w) = store.newest_world();
    let s = slot_{k}(&w, Ghost(store.db_at(e as nat)));
    (s.get(), Ghost(e))
}}

/// Every kept version's {kit} slot becomes invalid (the others stay).
pub fn invalidate_{k}(store: &GStore) {{
    let (mut c, g) = store.begin_write();
    let n = c.versions.len();
    let mut i: usize = 0;
    while i < n
        invariant
            i <= n,
            n == c.versions.len(),
            cell_ok(c, store.timeline()),
            g.store() == *store,
        decreases n - i,
    {{
        let v = c.base + i as u64;
        let ghost d = store.db_at(v as nat);
        assert(c.versions@[i as int].ok((store.timeline())((c.base + i) as nat)));
        let w2 = replace_{k}(&c.versions[i], Slot::Invalid, Ghost(d), Ghost(db_{k}(d)));
        assert(with_{k}(d, db_{k}(d)) == d);
        c.set(v, w2, Ghost(store.timeline()));
        i += 1;
    }}
    g.end(c);
}}
""")
    w("} // verus!")
    (out / "crate" / "src" / "world.rs").write_text("\n".join(lines) + "\n")

    (out / "crate" / "src" / "lib.rs").write_text(
        f"// GENERATED by scripts/gen_verus_world.py.  The {bench} world crate: world.rs is\n"
        "// verified; ffi.rs is the trusted C ABI.\n"
        "#![allow(unused_imports)]\n\npub mod world;\npub mod ffi;\n")

    f = []
    a = f.append
    a("// GENERATED by scripts/gen_verus_world.py.  DO NOT EDIT: regenerate.")
    a("//")
    a("// The world's C ABI.  TRUSTED (not verified): the host's contract enters")
    a("// here.  The ghost timeline is the database the host's commits make; a")
    a("// state handed to batch_set_* answers for its accelerator's projection of")
    a("// the next version (its kernel's apply / build proof, from the commit's")
    a("// captured changes); batch_finish's precondition (accelerators not set are")
    a("// unchanged by the commit) is the host's; epochs are the engine's.")
    a("#![allow(unused_imports, unused_variables, clippy::all)]")
    a("use std::ptr;")
    a("use std::sync::Arc;")
    a("use vstd::prelude::*;")
    a("use verus_substrate::store::*;")
    a("use verus_substrate::world::*;")
    a("use crate::world::*;")
    a("")
    a("/// A store with one version (0), every slot invalid.")
    a("#[no_mangle]")
    a(f"pub extern \"C\" fn {prefix}_new() -> *mut GStore {{")
    a("    Box::into_raw(Box::new(Store::new(0, <World as AuxWorld<GDb>>::invalid(), 0, Ghost::assume_new())))")
    a("}")
    a("")
    a("#[no_mangle]")
    a(f"pub unsafe extern \"C\" fn {prefix}_free(st: *mut GStore) {{")
    a("    if !st.is_null() {")
    a("        drop(Box::from_raw(st));")
    a("    }")
    a("}")
    a("")
    a("/// Mark a commit in flight, visible from engine epoch `from`.  1: marked; 0: one is already in flight.")
    a("#[no_mangle]")
    a(f"pub unsafe extern \"C\" fn {prefix}_begin(st: *const GStore, from: u64) -> i32 {{")
    a("    if (*st).begin(from) { 1 } else { 0 }")
    a("}")
    a("")
    a("#[no_mangle]")
    a(f"pub unsafe extern \"C\" fn {prefix}_abort(st: *const GStore) {{")
    a("    (*st).abort()")
    a("}")
    a("")
    a("/// A batch from the newest version, or NULL if none can follow it.")
    a("#[no_mangle]")
    a(f"pub unsafe extern \"C\" fn {prefix}_batch_new(st: *const GStore) -> *mut Batch {{")
    a("    match batch_new(&*st) {")
    a("        Some(b) => Box::into_raw(Box::new(b)),")
    a("        None => ptr::null_mut(),")
    a("    }")
    a("}")
    a("")
    a("#[no_mangle]")
    a(f"pub unsafe extern \"C\" fn {prefix}_batch_free(b: *mut Batch) {{")
    a("    if !b.is_null() {")
    a("        drop(Box::from_raw(b));")
    a("    }")
    a("}")
    a("")
    a("/// Install the batch (consumed) as the next version, current from engine")
    a("/// epoch `from`; keep the versions snapshots at or after `floor` select;")
    a("/// end_commit != 0 also ends the commit in flight.  0: appended; 1: stale.")
    a("#[no_mangle]")
    a(f"pub unsafe extern \"C\" fn {prefix}_install(st: *const GStore, b: *mut Batch, from: u64, floor: u64, end_commit: i32) -> i32 {{")
    a("    let p = batch_finish(*Box::from_raw(b));")
    a("    let r = if end_commit != 0 { (*st).commit(p, from, floor) } else { (*st).install(p, from, floor) };")
    a("    match r {")
    a("        Install::Applied => 0,")
    a("        Install::Stale => 1,")
    a("    }")
    a("}")
    a("")
    a("#[no_mangle]")
    a(f"pub unsafe extern \"C\" fn {prefix}_version_count(st: *const GStore) -> usize {{")
    a("    (*st).version_count()")
    a("}")
    a("")
    for k, kit in zip(idx, kits):
        a(f"// ---- {kit} ----")
        a("/// Replace its slot in the batch: s (a state from its build / apply, consumed) or NULL (invalid).")
        a("#[no_mangle]")
        a(f"pub unsafe extern \"C\" fn {prefix}_batch_set_{k}(b: *mut Batch, s: *mut S{k}) {{")
        a("    let state = if s.is_null() { None } else { Some(*Box::from_raw(s)) };")
        a(f"    ptr::write(b, batch_set_{k}(ptr::read(b), state));")
        a("}")
        a("")
        a("/// What a snapshot at `at` sees (0: the newest), waiting up to `tries` checks.")
        a("/// *status: 0 a state (returned; release it), 1 invalid, 2 pending, 3 not visible.")
        a("#[no_mangle]")
        a(f"pub unsafe extern \"C\" fn {prefix}_read_{k}(st: *const GStore, at: u64, tries: u64, status: *mut i32) -> *const S{k} {{")
        a(f"    let (code, s, _, _) = read_{k}(&*st, at, tries);")
        a("    if !status.is_null() {")
        a("        *status = code;")
        a("    }")
        a("    match s {")
        a("        Some(a) => Arc::into_raw(a),")
        a("        None => ptr::null(),")
        a("    }")
        a("}")
        a("")
        a("/// Its state in the newest version (release it), or NULL if invalid.")
        a("#[no_mangle]")
        a(f"pub unsafe extern \"C\" fn {prefix}_newest_{k}(st: *const GStore) -> *const S{k} {{")
        a(f"    match newest_{k}(&*st).0 {{")
        a("        Some(a) => Arc::into_raw(a),")
        a("        None => ptr::null(),")
        a("    }")
        a("}")
        a("")
        a("#[no_mangle]")
        a(f"pub unsafe extern \"C\" fn {prefix}_release_{k}(s: *const S{k}) {{")
        a("    if !s.is_null() {")
        a("        drop(Arc::from_raw(s));")
        a("    }")
        a("}")
        a("")
        a("#[no_mangle]")
        a(f"pub unsafe extern \"C\" fn {prefix}_invalidate_{k}(st: *const GStore) {{")
        a(f"    invalidate_{k}(&*st)")
        a("}")
        a("")
    (out / "crate" / "src" / "ffi.rs").write_text("\n".join(f) + "\n")

    h = [f"// GENERATED by scripts/gen_verus_world.py: the {bench} world's C ABI (crate/src/ffi.rs).",
         "#pragma once", "#include <stddef.h>", "#include <stdint.h>", "#ifdef __cplusplus", 'extern "C" {', "#endif",
         f"typedef struct {prefix}_store {prefix}_store;", f"typedef struct {prefix}_batch {prefix}_batch;",
         f"{prefix}_store *{prefix}_new(void);", f"void {prefix}_free({prefix}_store *st);",
         f"int32_t {prefix}_begin(const {prefix}_store *st, uint64_t from);", f"void {prefix}_abort(const {prefix}_store *st);",
         f"{prefix}_batch *{prefix}_batch_new(const {prefix}_store *st);", f"void {prefix}_batch_free({prefix}_batch *b);",
         f"int32_t {prefix}_install(const {prefix}_store *st, {prefix}_batch *b, uint64_t from, uint64_t floor, int32_t end_commit);",
         f"size_t {prefix}_version_count(const {prefix}_store *st);"]
    for k in idx:
        h += [f"void {prefix}_batch_set_{k}({prefix}_batch *b, void *state);",
              f"const void *{prefix}_read_{k}(const {prefix}_store *st, uint64_t at, uint64_t tries, int32_t *status);",
              f"const void *{prefix}_newest_{k}(const {prefix}_store *st);",
              f"void {prefix}_release_{k}(const void *state);",
              f"void {prefix}_invalidate_{k}(const {prefix}_store *st);"]
    h += ["#ifdef __cplusplus", "}", "#endif"]
    (out / f"{world}_verus.h").write_text("\n".join(h) + "\n")

    g = [f"// GENERATED by scripts/gen_verus_world.py: registers the {bench} world (one",
         "// verified store for every accelerator below) with the host kit.",
         '#include "accelerator_codegen/verus/verus_kit.hpp"',
         f'#include "{world}_verus.h"', "", "namespace {", "namespace kit = accelerator_codegen::verus_kit;", "",
         "const kit::World kWorld = {", f'    "{bench}",',
         "    [] { return static_cast<void *>(" + f"{prefix}_new()); }},",
         f"    [](void *st) {{ {prefix}_free(static_cast<{prefix}_store *>(st)); }},",
         f"    [](const void *st, uint64_t from) {{ return {prefix}_begin(static_cast<const {prefix}_store *>(st), from); }},",
         f"    [](const void *st) {{ {prefix}_abort(static_cast<const {prefix}_store *>(st)); }},",
         f"    [](const void *st) {{ return static_cast<void *>({prefix}_batch_new(static_cast<const {prefix}_store *>(st))); }},",
         f"    [](void *b) {{ {prefix}_batch_free(static_cast<{prefix}_batch *>(b)); }},",
         f"    [](const void *st, void *b, uint64_t from, uint64_t floor, int32_t end) {{",
         f"      return {prefix}_install(static_cast<const {prefix}_store *>(st), static_cast<{prefix}_batch *>(b), from, floor, end);",
         "    },",
         f"    [](const void *st) {{ return {prefix}_version_count(static_cast<const {prefix}_store *>(st)); }},",
         "    {"]
    for k, kit in zip(idx, kits):
        g += [f'        {{"{kit}",',
              f"         [](void *b, void *s) {{ {prefix}_batch_set_{k}(static_cast<{prefix}_batch *>(b), s); }},",
              f"         [](const void *st, uint64_t at, uint64_t tries, int32_t *status) {{",
              f"           return {prefix}_read_{k}(static_cast<const {prefix}_store *>(st), at, tries, status);",
              "         },",
              f"         [](const void *st) {{ return {prefix}_newest_{k}(static_cast<const {prefix}_store *>(st)); }},",
              f"         [](const void *s) {{ {prefix}_release_{k}(s); }},",
              f"         [](const void *st) {{ {prefix}_invalidate_{k}(static_cast<const {prefix}_store *>(st)); }}}},"]
    g += ["    },", "};", "", "const bool kRegistered = (kit::RegisterWorld(&kWorld), true);", "", "} // namespace"]
    (out / "world_glue.cpp").write_text("\n".join(g) + "\n")
    print(f"generated {out} ({n} accelerators)")


if __name__ == "__main__":
    main()
