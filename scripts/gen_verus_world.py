#!/usr/bin/env python3
"""Generate a benchmark's Verus world crate: ONE verified aux store for every
accelerator of the database (one reader-writer lock, one version per commit,
every accelerator's slot answering for the same database version).

    python3 scripts/gen_verus_world.py tpch tpch_q1_vgen tpch_q2_vgen ...

writes accelerators/<bench>/verus_world/<bench>_world/:
  crate/src/lib.rs     the crate (links every kit crate as an rlib)
  crate/src/world.rs   VERIFIED: the world type, the base a commit is built on,
                       the batch (each slot put from a state staged on that
                       base by the kit's stage_* functions), per-accelerator
                       readings
  crate/src/ffi.rs     TRUSTED C ABI (the host's contract is assumed here)
  <bench>_world_verus.h
  world_glue.cpp       registers the C ABI with the host kit (verus_kit.hpp)

Build: scripts/build_verus_world.sh (kits as --rlib first).
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent



def main() -> None:
    bench, kits = sys.argv[1], sys.argv[2:]
    if not kits:
        sys.exit("usage: gen_verus_world.py <bench> <kit crate>...")
    world = f"{bench}_world"
    prefix = f"{bench}w"
    out = ROOT / "accelerators" / bench / "verus_world" / world
    (out / "crate" / "src").mkdir(parents=True, exist_ok=True)
    n = len(kits)
    idx = range(1, n + 1)

    lines = []
    w = lines.append
    w("// GENERATED by scripts/gen_verus_world.py.  DO NOT EDIT: regenerate.")
    w("//")
    w(f"// The {bench} world: one verified aux store for every accelerator (one")
    w("// reader-writer lock, one version per database commit).  Version v's world")
    w("// holds one slot per accelerator; slot k answers for accelerator k's")
    w("// projection of the database at v (`db_k`).")
    w("//")
    w("// A commit's version is assembled outside the lock.  Every accelerator the")
    w("// commit changes stages its slot with its kit's stage_apply / stage_build on")
    w("// its part of the newest version (`base_k` / `head_k` of a `GBase`), and the")
    w("// `Batch` made from that GBase takes it (`put_k`) only if the slot was staged")
    w("// on that very base; any other slot becomes invalid.  So every put state is")
    w("// produced by verified code from slot k of the batch's base world.")
    w("// Readers resolve their snapshot under the read lock (substrate store.rs:")
    w("// the snapshot and commit-order theorems) and are narrowed to their")
    w("// accelerator (`read_k`); the kit's `answer` is Theorem 5.4 on that reading.")
    w("#![allow(unused_imports)]")
    w("use vstd::prelude::*;")
    w("use std::sync::Arc;")
    w("use verus_substrate::store::*;")
    w("use verus_substrate::world::*;")
    w("")
    w("verus! {")
    w("")
    for k, kit in zip(idx, kits):
        w(f"pub type S{k} = {kit}_verus::kernel::State;")
        w(f"pub type D{k} = {kit}_verus::gen_spec::Db;")
    w("")
    w(f"/// One slot per accelerator ({', '.join(kits)}), flat: the world answers")
    w("/// for a database when every slot answers for its accelerator's projection.")
    w("pub struct World {")
    for k in idx:
        w(f"    pub s{k}: Slot<S{k}>,")
    w("}")
    w("")
    w("/// The database as each accelerator sees it (its projection), side by side.")
    w("pub struct GDb {")
    for k in idx:
        w(f"    pub d{k}: D{k},")
    w("}")
    w("")
    w("impl AuxWorld<GDb> for World {")
    w("    open spec fn ok(self, d: GDb) -> bool {")
    w("        " + "\n        && ".join(f"self.s{k}.ok(d.d{k})" for k in idx))
    w("    }")
    w("")
    w("    fn invalid() -> (w: Self) {")
    w("        World { " + ", ".join(f"s{k}: Slot::Invalid" for k in idx) + " }")
    w("    }")
    w("")
    w("    fn share(&self) -> (w: Self) {")
    w("        World {")
    for k in idx:
        w(f"            s{k}: <Slot<S{k}> as AuxWorld<D{k}>>::share(&self.s{k}),")
    w("        }")
    w("    }")
    w("}")
    w("")
    w("pub type GStore = Store<GDb, World>;")
    w("pub type GPrepared = Prepared<GDb, World>;")
    w("")
    for k, kit in zip(idx, kits):
        w(f"/// {kit}'s projection of the database.")
        w(f"pub open spec fn db_{k}(d: GDb) -> D{k} {{")
        w(f"    d.d{k}")
        w("}")
        w("")
        w(f"/// {kit}'s projection of a timeline.")
        w(f"pub open spec fn tl_{k}(t: spec_fn(nat) -> GDb) -> spec_fn(nat) -> D{k} {{")
        w(f"    |n: nat| db_{k}(t(n))")
        w("}")
        w("")
        w(f"/// d with {kit}'s projection replaced by x.")
        w(f"pub open spec fn with_{k}(d: GDb, x: D{k}) -> GDb {{")
        w("    GDb { " + ", ".join(f"d{j}: x" if j == k else f"d{j}: d.d{j}" for j in idx) + " }")
        w("}")
        w("")
        w(f"/// w with {kit}'s slot replaced by s (every other slot shared).")
        w(f"pub fn replace_{k}(w: &World, s: Slot<S{k}>, Ghost(d): Ghost<GDb>, Ghost(x): Ghost<D{k}>) -> (r: World)")
        w("    requires")
        w("        w.ok(d),")
        w("        s.ok(x),")
        w("    ensures")
        w(f"        r.ok(with_{k}(d, x)),")
        w("{")
        w("    World {")
        for j in idx:
            if j == k:
                w(f"        s{j}: s,")
            else:
                w(f"        s{j}: <Slot<S{j}> as AuxWorld<D{j}>>::share(&w.s{j}),")
        w("    }")
        w("}")
        w("")
        w(f"/// {kit}'s slot of w.")
        w(f"pub fn slot_{k}(w: &World, Ghost(d): Ghost<GDb>) -> (r: &Slot<S{k}>)")
        w("    requires")
        w("        w.ok(d),")
        w("    ensures")
        w(f"        r.ok(db_{k}(d)),")
        w("{")
        w(f"    &w.s{k}")
        w("}")
        w("")
    w("/// The newest version e: its world, answering for the database at e, and one")
    w("/// head per accelerator (the version and its projected timeline) that the")
    w("/// slots staged on this base carry.")
    w("pub struct GBase {")
    w("    e: u64,")
    w("    w: World,")
    w("    timeline: Ghost<spec_fn(nat) -> GDb>,")
    for k in idx:
        w(f"    h{k}: Head<D{k}>,")
    w("}")
    w("")
    w("impl GBase {")
    w("    #[verifier::type_invariant]")
    w("    spec fn wf(self) -> bool {")
    w("        &&& self.e < u64::MAX")
    w("        &&& self.w.ok((self.timeline@)(self.e as nat))")
    for k in idx:
        w(f"        &&& self.h{k}.epoch() == self.e && self.h{k}.timeline() == tl_{k}(self.timeline@)")
    w("    }")
    w("")
    w("    pub closed spec fn epoch(self) -> u64 {")
    w("        self.e")
    w("    }")
    w("")
    w("    pub closed spec fn timeline(self) -> spec_fn(nat) -> GDb {")
    w("        self.timeline@")
    w("    }")
    w("}")
    w("")
    w("/// The newest version as a base to stage the next one on (None if no version can follow it).")
    w("pub fn gbase_new(store: &GStore) -> (r: Option<Arc<GBase>>)")
    w("    ensures")
    w("        r matches Some(b) ==> b.timeline() == store.timeline(),")
    w("{")
    w("    let (e, w) = store.newest_world();")
    w("    if e < u64::MAX {")
    w("        let ghost t = store.timeline();")
    w("        Some(Arc::new(GBase {")
    w("            e,")
    w("            w,")
    w("            timeline: Ghost(t),")
    for k in idx:
        w(f"            h{k}: Head::new(e, Ghost(tl_{k}(t))),")
    w("        }))")
    w("    } else {")
    w("        None")
    w("    }")
    w("}")
    w("")
    for k, kit in zip(idx, kits):
        w(f"/// {kit}'s state in the base (None if its slot is invalid).")
        w(f"pub fn base_{k}(gb: &GBase) -> (r: Option<Base<D{k}, S{k}>>)")
        w("    ensures")
        w(f"        r matches Some(b) ==> b.epoch() == gb.epoch() && b.timeline() == tl_{k}(gb.timeline()),")
        w("{")
        w("    proof {")
        w("        use_type_invariant(gb);")
        w("    }")
        w(f"    match &gb.w.s{k} {{")
        w(f"        Slot::Valid(a) => Some(Base::new(gb.h{k}.share(), a.clone())),")
        w("        Slot::Invalid => None,")
        w("    }")
        w("}")
        w("")
        w(f"/// {kit}'s head of the base (to stage a build on).")
        w(f"pub fn head_{k}(gb: &GBase) -> (r: Head<D{k}>)")
        w("    ensures")
        w(f"        r.epoch() == gb.epoch() && r.timeline() == tl_{k}(gb.timeline()),")
        w("{")
        w("    proof {")
        w("        use_type_invariant(gb);")
        w("    }")
        w(f"    gb.h{k}.share()")
        w("}")
        w("")
    w("""/// The next version's world, assembled outside the lock on a base: each
/// accelerator the commit changes gets its staged slot (answering for its
/// projection at e + 1), every other slot is carried from the base.
/// Invariant: the world answers for `target`, the database with each replaced
/// projection at e + 1 and every carried one at e.
pub struct Batch {
    base: Arc<GBase>,
    next: World,
    target: Ghost<GDb>,
}

impl Batch {
    #[verifier::type_invariant]
    spec fn wf(self) -> bool {
        &&& self.next.ok(self.target@)
    }

    pub closed spec fn epoch(self) -> u64 {
        self.base.epoch()
    }

    pub closed spec fn target(self) -> GDb {
        self.target@
    }

    pub closed spec fn timeline(self) -> spec_fn(nat) -> GDb {
        self.base.timeline()
    }

    /// The database at the version this batch prepares (e + 1).
    pub open spec fn next_db(self) -> GDb {
        (self.timeline())((self.epoch() + 1) as nat)
    }
}

/// A batch on a base, every slot carried.
pub fn batch_new(base: &Arc<GBase>) -> (r: Batch)
    ensures
        r.epoch() == base.epoch(),
        r.timeline() == base.timeline(),
        r.target() == (base.timeline())(base.epoch() as nat),
{
    proof {
        use_type_invariant(&**base);
    }
    Batch { base: base.clone(), next: base.w.share(), target: Ghost((base.timeline@)(base.e as nat)) }
}

/// The next version (consumes the batch).  HOST CONTRACT (the requires): the
/// accelerators the batch did not replace are unchanged by this commit, so
/// the target is the database at e + 1.
pub fn batch_finish(b: Batch) -> (p: GPrepared)
    requires
        b.target() == b.next_db(),
    ensures
        p.epoch() == b.epoch(),
        p.timeline() == b.timeline(),
{
    proof {
        use_type_invariant(&b);
        use_type_invariant(&*b.base);
    }
    Prepared::new(b.base.e, b.next, b.base.timeline)
}
""")
    for k, kit in zip(idx, kits):
        w(f"""/// Replace {kit}'s slot by the one staged on this batch's base: true.  A slot
/// staged on another base is not taken: the slot becomes invalid (false).
pub fn put_{k}(b: Batch, st: Staged<D{k}, S{k}>) -> (r: (Batch, bool))
    ensures
        r.0.epoch() == b.epoch(),
        r.0.timeline() == b.timeline(),
        r.0.target() == with_{k}(b.target(), db_{k}(b.next_db())),
{{
    proof {{
        use_type_invariant(&b);
        use_type_invariant(&*b.base);
    }}
    let same = st.head().same(&b.base.h{k});
    let ghost (se, stl) = (st.epoch(), st.timeline());
    let slot = if same {{
        st.into_slot()
    }} else {{
        Slot::Invalid
    }};
    assert(same ==> slot.ok(db_{k}(b.next_db())));
    let next = replace_{k}(&b.next, slot, Ghost(b.target@), Ghost(db_{k}(b.next_db())));
    (Batch {{ base: b.base, next, target: Ghost(with_{k}(b.target@, db_{k}(b.next_db()))) }}, same)
}}

/// Make {kit}'s slot invalid in the batch.
pub fn put_invalid_{k}(b: Batch) -> (r: Batch)
    ensures
        r.epoch() == b.epoch(),
        r.timeline() == b.timeline(),
        r.target() == with_{k}(b.target(), db_{k}(b.next_db())),
{{
    proof {{
        use_type_invariant(&b);
    }}
    let next = replace_{k}(&b.next, Slot::Invalid, Ghost(b.target@), Ghost(db_{k}(b.next_db())));
    Batch {{ base: b.base, next, target: Ghost(with_{k}(b.target@, db_{k}(b.next_db()))) }}
}}

/// What a snapshot at engine epoch `at` sees of {kit} (waiting up to `tries`
/// checks for a pending commit).  0: a reading narrowed to its slot (the kit's
/// `answer` runs on it: Theorem 5.4); 1: that version's slot is invalid; 2: a
/// commit in flight may be visible; 3: the version was evicted.
pub fn read_{k}(store: &GStore, at: u64, tries: u64) -> (r: (i32, Option<Reading<D{k}, Slot<S{k}>>>))
    ensures
        r.0 == 0 ==> r.1 is Some,
        0 <= r.0 <= 3,
        r.1 matches Some(g) ==> g.at() == at && g.db() == db_{k}(store.db_at(g.version() as nat))
            && g.snapshot_db() == db_{k}(store.snap_db(at)),
{{
    match store.read(at, tries) {{
        Read::Found(g) => {{
            let slot = <Slot<S{k}> as AuxWorld<D{k}>>::share(slot_{k}(g.world(), Ghost(g.db())));
            match slot {{
                Slot::Invalid => (1, None),
                Slot::Valid(_) => (0, Some(g.narrow(Ghost(|d: GDb| db_{k}(d)), slot))),
            }}
        }},
        Read::Pending => (2, None),
        Read::NotVisible => (3, None),
    }}
}}

/// Every kept version's {kit} slot becomes invalid (the others stay).
pub fn invalidate_{k}(store: &GStore) {{
    let (mut c, g) = store.begin_write();
    let n = c.versions.len();
    let mut i: usize = 0;
    while i < n
        invariant
            i <= n,
            n == c.versions.len(),
            cell_ok(c, store.timeline()),
            exact_ok(c, store.timeline(), store.engine()),
            g.store() == *store,
        decreases n - i,
    {{
        let v = c.base + i as u64;
        let ghost d = store.db_at(v as nat);
        assert(c.versions@[i as int].ok((store.timeline())((c.base + i) as nat)));
        let w2 = replace_{k}(&c.versions[i], Slot::Invalid, Ghost(d), Ghost(db_{k}(d)));
        assert(with_{k}(d, db_{k}(d)) == d);
        c.set(v, w2, Ghost(store.timeline()));
        i += 1;
    }}
    g.end(c);
}}
""")
