"""Generate Rocq + Dafny AuxSpec artifacts from neutral YAML specs.

Cross-prover seam: shared Spec text (hash recorded in generated headers).
Rocq uses FoldSpec / AuxAnswerSpec; Dafny proves TwinOp ≡ SpecOp then
FoldTwin = FoldSpec.

Usage:
  python3 gen_auxspec.py [--check]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
VERIF = ROOT.parent
FORMALSQL_GEN = VERIF / "formalsql" / "generated"
Q1_DAFNY_GEN = VERIF / "q1" / "dafny" / "generated"


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def load_spec(path: Path) -> dict:
    with path.open() as f:
        return yaml.safe_load(f)


def canon_json(spec: dict) -> bytes:
    return json.dumps(spec, sort_keys=True, separators=(",", ":")).encode()


def emit_q1_rocq(spec: dict, digest: str) -> str:
    return f"""(* GENERATED by auxspec/gen_auxspec.py — DO NOT EDIT.
   source_sha256={digest}
   query={spec['query']}
*)

(** Q1 AuxSpec: FoldSpec / ViewSpec / FinalizeSpec / AuxAnswerSpec.
    TwinOp ≡ SpecOp and FoldTwin = FoldSpec live in Dafny, not here. *)

Require Import List ZArith Bool.
Import ListNotations.
Open Scope Z_scope.

Module Q1AuxSpec.

Record Stats : Type := mkStats {{
  count : Z;
  sum_qty : Z;
  sum_base_price : Z;
  sum_disc_price : Z;
  sum_charge : Z;
  sum_discount : Z
}}.

Definition EmptyStats : Stats :=
  mkStats 0 0 0 0 0 0.

Record Row : Type := mkRow {{
  shipdate : Z;
  qty : Z;
  price : Z;
  disc : Z;
  tax : Z;
  rf : Z;
  ls : Z
}}.

Definition Pack (rf ls : Z) : Z := rf * 256 + ls.

Definition RowKey (r : Row) : Z := Pack (rf r) (ls r).

(** SpecApply — contribution of one row with sign (+1 insert / -1 delete). *)
Definition SpecApply (s : Stats) (r : Row) (sign : Z) : Stats :=
  let disc_price := price r * (100 - disc r) in
  mkStats
    (count s + sign)
    (sum_qty s + sign * qty r)
    (sum_base_price s + sign * price r)
    (sum_disc_price s + sign * disc_price)
    (sum_charge s + sign * disc_price * (100 + tax r))
    (sum_discount s + sign * disc r).

Definition SpecMerge (a b : Stats) : Stats :=
  mkStats
    (count a + count b)
    (sum_qty a + sum_qty b)
    (sum_base_price a + sum_base_price b)
    (sum_disc_price a + sum_disc_price b)
    (sum_charge a + sum_charge b)
    (sum_discount a + sum_discount b).

(** Day×group abstract store as association list (finite map surrogate). *)
Definition CellKey : Type := (Z * Z)%type.
Definition Store : Type := list (CellKey * Stats).

Definition cellkey_eqb (a b : CellKey) : bool :=
  Z.eqb (fst a) (fst b) && Z.eqb (snd a) (snd b).

Fixpoint store_get (st : Store) (k : CellKey) : Stats :=
  match st with
  | [] => EmptyStats
  | (k', s) :: rest => if cellkey_eqb k k'
                       then s else store_get rest k
  end.

(** Map-faithful list update: drop any prior binding of [k], then write [s]
    (or omit when count is zero). Matches Dafny [Store] map overwrite/erase. *)
Definition store_remove (st : Store) (k : CellKey) : Store :=
  filter (fun '(k', _) => negb (cellkey_eqb k' k)) st.

Definition SpecApplyDelta (st : Store) (r : Row) (sign : Z) : Store :=
  let k := (shipdate r, RowKey r) in
  let s2 := SpecApply (store_get st k) r sign in
  if Z.eqb (count s2) 0 then store_remove st k
  else (k, s2) :: store_remove st k.

Fixpoint FoldSpec (db : list Row) : Store :=
  match db with
  | [] => []
  | r :: rest => SpecApplyDelta (FoldSpec rest) r 1
  end.

(** Merge stats for one gkey into an association list. *)
Fixpoint keystore_put (acc : list (Z * Stats)) (gkey : Z) (s : Stats)
  : list (Z * Stats) :=
  match acc with
  | [] => [(gkey, s)]
  | (k, s0) :: rest =>
      if Z.eqb k gkey then (k, SpecMerge s0 s) :: rest
      else (k, s0) :: keystore_put rest gkey s
  end.

(** ViewSpec: keep cells with day <= cutoff; merge by gkey. *)
Fixpoint SpecView (st : Store) (cutoff : Z) : list (Z * Stats) :=
  match st with
  | [] => []
  | ((day, gkey), s) :: rest =>
      let acc := SpecView rest cutoff in
      if Z.leb day cutoff then keystore_put acc gkey s else acc
  end.

Record OutRow : Type := mkOutRow {{
  out_rf : Z;
  out_ls : Z;
  out_sum_qty : Z;
  out_sum_base : Z;
  out_sum_disc_price : Z;
  out_sum_charge : Z;
  out_sum_discount : Z;
  out_avg_qty : Z;
  out_avg_price : Z;
  out_avg_disc : Z;
  out_count : Z
}}.

Definition Unpack (gkey : Z) : (Z * Z) :=
  (gkey / 256, Z.modulo gkey 256).

(** PostgreSQL NUMERIC AVG rounding: ties away from zero (FormalSQL
    [numeric_round_quot]). Applied to scale-2 integer embeddings for Twin
    correspondence; EmbedResult uses FormalSQL [numeric_div_at_scales] for
    the FormalSQL observation (data-dependent display scale). *)
Definition AvgRound (numerator denominator : Z) : Z :=
  let quotient := Z.quot numerator denominator in
  let remainder := Z.rem numerator denominator in
  if (2 * Z.abs remainder >=? Z.abs denominator)%Z
  then quotient + (if (numerator * denominator <? 0)%Z then (-1) else 1)
  else quotient.

Definition SpecFinalizeOne (gkey : Z) (s : Stats) : list OutRow :=
  if Z.leb (count s) 0 then []
  else
    let '(rf, ls) := Unpack gkey in
    [mkOutRow rf ls
       (sum_qty s) (sum_base_price s) (sum_disc_price s) (sum_charge s)
       (sum_discount s)
       (AvgRound (sum_qty s) (count s))
       (AvgRound (sum_base_price s) (count s))
       (AvgRound (sum_discount s) (count s))
       (count s)].

Fixpoint SpecFinalize (entries : list (Z * Stats)) : list OutRow :=
  match entries with
  | [] => []
  | (gkey, s) :: rest => SpecFinalizeOne gkey s ++ SpecFinalize rest
  end.

(** ORDER BY (l_returnflag, l_linestatus) ascending.  FormalSQL lowers the Q1
    [ORDER BY] to [SortAscNullsLast l_returnflag; SortAscNullsLast l_linestatus]
    on the single-char output columns; ascending string order on one-char codes
    is ascending order on the [Z] ASCII codes [out_rf]/[out_ls].  We finalize
    with an insertion sort by [(out_rf, out_ls)] so [AuxAnswerSpec] matches the
    unique sorted FormalSQL observation (group keys are distinct). *)
Definition OutRowLe (a b : OutRow) : bool :=
  if Z.eqb (out_rf a) (out_rf b)
  then Z.leb (out_ls a) (out_ls b)
  else Z.leb (out_rf a) (out_rf b).

Fixpoint OutRowInsert (x : OutRow) (l : list OutRow) : list OutRow :=
  match l with
  | [] => [x]
  | y :: ys => if OutRowLe x y then x :: y :: ys else y :: OutRowInsert x ys
  end.

Fixpoint OutRowSort (l : list OutRow) : list OutRow :=
  match l with
  | [] => []
  | x :: xs => OutRowInsert x (OutRowSort xs)
  end.

Definition AuxAnswerSpec (db : list Row) (cutoff : Z) : list OutRow :=
  OutRowSort (SpecFinalize (SpecView (FoldSpec db) cutoff)).

End Q1AuxSpec.
"""


def emit_q1_dafny(spec: dict, digest: str) -> str:
    return f"""// GENERATED by auxspec/gen_auxspec.py — DO NOT EDIT.
// source_sha256={digest}
// query={spec['query']}

module Q1AuxSpec {{

  datatype Stats = Stats(
    count: int,
    sum_qty: int,
    sum_base_price: int,
    sum_disc_price: int,
    sum_charge: int,
    sum_discount: int
  )

  ghost function EmptyStats(): Stats {{
    Stats(0, 0, 0, 0, 0, 0)
  }}

  datatype Row = Row(
    shipdate: int,
    qty: int,
    price: int,
    disc: int,
    tax: int,
    rf: int,
    ls: int
  )

  ghost function Pack(rf: int, ls: int): int {{
    rf * 256 + ls
  }}

  ghost function RowKey(r: Row): int
    requires 0 <= r.rf < 256 && 0 <= r.ls < 256
  {{
    Pack(r.rf, r.ls)
  }}

  ghost function SpecApply(
    s: Stats,
    r: Row,
    sign: int
  ): Stats {{
    var disc_price := r.price * (100 - r.disc);
    Stats(
      s.count + sign,
      s.sum_qty + sign * r.qty,
      s.sum_base_price + sign * r.price,
      s.sum_disc_price + sign * disc_price,
      s.sum_charge + sign * disc_price * (100 + r.tax),
      s.sum_discount + sign * r.disc
    )
  }}

  ghost function SpecMerge(a: Stats, b: Stats): Stats {{
    Stats(
      a.count + b.count,
      a.sum_qty + b.sum_qty,
      a.sum_base_price + b.sum_base_price,
      a.sum_disc_price + b.sum_disc_price,
      a.sum_charge + b.sum_charge,
      a.sum_discount + b.sum_discount
    )
  }}

  datatype CellKey = CellKey(day: int, gkey: int)
  type Store = map<CellKey, Stats>

  ghost function SpecGet(store: Store, k: CellKey): Stats {{
    if k in store then store[k] else EmptyStats()
  }}

  ghost function SpecApplyDelta(store: Store, r: Row, sign: int): Store
    requires 0 <= r.rf < 256 && 0 <= r.ls < 256
  {{
    var k := CellKey(r.shipdate, RowKey(r));
    var s2 := SpecApply(SpecGet(store, k), r, sign);
    if s2.count == 0 then
      map k' | k' in store && k' != k :: store[k']
    else
      store[k := s2]
  }}

  ghost function FoldSpec(db: seq<Row>): Store
    requires forall i :: 0 <= i < |db| ==> 0 <= db[i].rf < 256 && 0 <= db[i].ls < 256
  {{
    if |db| == 0 then map[]
    else SpecApplyDelta(FoldSpec(db[..|db|-1]), db[|db|-1], 1)
  }}

  type KeyStore = map<int, Stats>

  ghost function SpecGetKey(m: KeyStore, g: int): Stats {{
    if g in m then m[g] else EmptyStats()
  }}

  // Deterministic View (Rocq list-fold / twin Compose style): filter by cutoff,
  // then SpecApply by group key. Extensional equal to merging FoldSpec day-cells.
  ghost function SpecViewFromDB(db: seq<Row>, cutoff: int): KeyStore
    requires forall i :: 0 <= i < |db| ==> 0 <= db[i].rf < 256 && 0 <= db[i].ls < 256
    decreases |db|
  {{
    if |db| == 0 then
      map[]
    else
      var rest := SpecViewFromDB(db[..|db| - 1], cutoff);
      var r := db[|db| - 1];
      if r.shipdate <= cutoff then
        var g := RowKey(r);
        rest[g := SpecApply(SpecGetKey(rest, g), r, 1)]
      else
        rest
  }}

  ghost function SpecViewMergeCell(acc: KeyStore, k: CellKey, s: Stats, cutoff: int): KeyStore {{
    if k.day <= cutoff then
      var g := k.gkey;
      acc[g := SpecMerge(if g in acc then acc[g] else EmptyStats(), s)]
    else
      acc
  }}

  ghost function SpecViewFromKeys(store: Store, keys: set<CellKey>, cutoff: int): KeyStore
    requires keys <= store.Keys
    decreases |keys|
  {{
    if keys == {{}} then map[]
    else
      var k :| k in keys;
      SpecViewMergeCell(SpecViewFromKeys(store, keys - {{k}}, cutoff), k, store[k], cutoff)
  }}

  // Store-merge View (same merges as SpecViewFromDB on FoldSpec images).
  ghost function SpecView(store: Store, cutoff: int): KeyStore {{
    SpecViewFromKeys(store, store.Keys, cutoff)
  }}

  datatype OutRow = OutRow(
    rf: int,
    ls: int,
    sum_qty: int,
    sum_base_price: int,
    sum_disc_price: int,
    sum_charge: int,
    sum_discount: int,
    avg_qty: int,
    avg_price: int,
    avg_disc: int,
    count_order: int
  )

  ghost function Unpack(gkey: int): (int, int) {{
    (gkey / 256, gkey % 256)
  }}

  // PostgreSQL NUMERIC AVG: ties away from zero (FormalSQL numeric_round_quot).
  ghost function AvgRound(numerator: int, denominator: int): int
    requires denominator != 0
  {{
    var quotient := numerator / denominator;
    var remainder := numerator % denominator;
    if 2 * (if remainder < 0 then -remainder else remainder)
         >= (if denominator < 0 then -denominator else denominator) then
      quotient + (if numerator * denominator < 0 then -1 else 1)
    else
      quotient
  }}

  ghost function SpecFinalizeOne(gkey: int, s: Stats): seq<OutRow> {{
    if s.count <= 0 then []
    else
      var p := Unpack(gkey);
      [OutRow(p.0, p.1, s.sum_qty, s.sum_base_price, s.sum_disc_price, s.sum_charge,
              s.sum_discount,
              AvgRound(s.sum_qty, s.count), AvgRound(s.sum_base_price, s.count),
              AvgRound(s.sum_discount, s.count), s.count)]
  }}

  ghost function SpecFinalizeFromKeys(entries: KeyStore, keys: set<int>): seq<OutRow>
    requires keys <= entries.Keys
    decreases |keys|
  {{
    if keys == {{}} then []
    else
      var g :| g in keys;
      SpecFinalizeOne(g, entries[g]) + SpecFinalizeFromKeys(entries, keys - {{g}})
  }}

  ghost function SpecFinalize(entries: KeyStore): seq<OutRow> {{
    SpecFinalizeFromKeys(entries, entries.Keys)
  }}

  // ORDER BY (l_returnflag, l_linestatus) ascending. Ascending string order on
  // one-char codes is ascending order on the (rf, ls) integer ASCII codes.
  ghost predicate OutRowLe(a: OutRow, b: OutRow) {{
    a.rf < b.rf || (a.rf == b.rf && a.ls <= b.ls)
  }}

  ghost function OutRowInsert(x: OutRow, l: seq<OutRow>): seq<OutRow>
    decreases |l|
  {{
    if |l| == 0 then [x]
    else if OutRowLe(x, l[0]) then [x] + l
    else [l[0]] + OutRowInsert(x, l[1..])
  }}

  ghost function OutRowSort(l: seq<OutRow>): seq<OutRow>
    decreases |l|
  {{
    if |l| == 0 then []
    else OutRowInsert(l[0], OutRowSort(l[1..]))
  }}

  ghost function AuxAnswerSpec(db: seq<Row>, cutoff: int): seq<OutRow>
    requires forall i :: 0 <= i < |db| ==> 0 <= db[i].rf < 256 && 0 <= db[i].ls < 256
  {{
    // SpecViewFromDB ≡ SpecView(FoldSpec(db)) (day-cell merge); deterministic for Dafny.
    OutRowSort(SpecFinalize(SpecViewFromDB(db, cutoff)))
  }}

}}
"""



SPECS = {
    "q1": {
        "yaml": ROOT / "q1" / "spec.yaml",
        "rocq": FORMALSQL_GEN / "Q1AuxSpec.v",
        "dafny": Q1_DAFNY_GEN / "Q1AuxSpec.dfy",
        "emit_rocq": emit_q1_rocq,
        "emit_dafny": emit_q1_dafny,
    },
}


def generate(check: bool) -> int:
    mismatched = []
    for name, cfg in SPECS.items():
        spec = load_spec(cfg["yaml"])
        digest = sha256_bytes(canon_json(spec))
        rocq = cfg["emit_rocq"](spec, digest)
        dafny = cfg["emit_dafny"](spec, digest)
        for path, content in ((cfg["rocq"], rocq), (cfg["dafny"], dafny)):
            path.parent.mkdir(parents=True, exist_ok=True)
            if check:
                if not path.exists() or path.read_text() != content:
                    mismatched.append(str(path))
            else:
                path.write_text(content)
                print(f"wrote {path} sha={digest[:12]}")
    if check and mismatched:
        print("AuxSpec out of date:", *mismatched, sep="\n  ", file=sys.stderr)
        return 1
    if check:
        print("AuxSpec artifacts up to date")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    return generate(args.check)


if __name__ == "__main__":
    sys.exit(main())
