CREATE TABLE cust (c_id INTEGER NOT NULL, c_name VARCHAR(20) NOT NULL, c_state CHAR(2) NOT NULL);
CREATE TABLE orders (o_id INTEGER NOT NULL, o_cust INTEGER NOT NULL, o_amt DECIMAL(10,2) NOT NULL, o_day DATE NOT NULL);
CREATE TABLE returns (r_id INTEGER NOT NULL, r_cust INTEGER NOT NULL, r_amt DECIMAL(10,2) NOT NULL);
